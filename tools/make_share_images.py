def og_block(title, desc, url, image):
    e = lambda s: html.escape(s, quote=True)
    return (f'<!-- share-preview:start (generated by tools/make_share_images.py) -->\n'
            f'<meta name="description" content="{e(desc)}">\n'
            f'<meta property="og:type" content="website">\n<meta property="og:site_name" content="Bounce Lab">\n'
            f'<meta property="og:title" content="{e(title)}">\n<meta property="og:description" content="{e(desc)}">\n'
            f'<meta property="og:url" content="{e(url)}">\n<meta property="og:image" content="{e(image)}">\n'
            f'<meta property="og:image:width" content="1200"><meta property="og:image:height" content="630">\n'
            f'<meta name="twitter:card" content="summary_large_image">\n'
            f'<!-- share-preview:end -->\n')

def write_tags(page: Path, block: str):
    s = page.read_text()
    s = re.sub(r"<!-- share-preview:start.*?share-preview:end -->\n", "", s, flags=re.S)
    i = s.index("</head>")
    # put tags before the lab script line if present, else before </head>
    j = s.find('<script src="../../lab/lab.js"')
    at = j if 0 <= j < i else i
    page.write_text(s[:at] + block + s[at:])

async def main():
    games = load_games()
    srv = subprocess.Popen([sys.executable, "-m", "http.server", str(PORT)], cwd=ROOT, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    time.sleep(1)
    try:
        async with async_playwright() as p:
            b = await p.chromium.launch(executable_path=CHROME, args=["--no-sandbox", "--use-gl=swiftshader", "--enable-webgl", "--ignore-gpu-blocklist"])
            phone = await b.new_context(viewport={"width": 390, "height": 844}, device_scale_factor=2)
            card = await b.new_context(viewport={"width": 1200, "height": 630}, device_scale_factor=1)
            for g in games:
                pg = await phone.new_page()
                await pg.goto(f"http://localhost:{PORT}/games/{g['id']}/index.html", wait_until="load")
                await pg.add_style_tag(content="#bl-root{display:none!important}")
                await pg.wait_for_timeout(3500)
                shot = base64.b64encode(await pg.screenshot()).decode()
                await pg.close()
                title = g["title"].upper()
                page = CARD.format(c=g.get("color", "#5ef2ff"), fs=110 if len(title) <= 7 else 86, title=html.escape(title),
                                   tagline=html.escape(g.get("tagline", "")), ver=html.escape(g.get("version", "")),
                                   icon=ICONS.get(g.get("icon"), f'<text x="0" y="22" text-anchor="middle" font-size="64" fill="#fff" stroke="none" font-family="Orbitron">{html.escape(title[:1])}</text>'), shot=shot)
                cp = await card.new_page(); await cp.set_content(page); await cp.wait_for_timeout(1200)
                out = ROOT / "games" / g["id"] / "share.jpg"
                await cp.screenshot(path=str(out), type="jpeg", quality=84); await cp.close()
                url = SITE + f"games/{g['id']}/"
                desc = (g.get("tagline", "") + ". " + g.get("description", "")).strip(". ")
                write_tags(ROOT / "games" / g["id"] / "index.html", og_block(f"{g['title']} · Bounce Lab", desc, url, url + "share.jpg"))
                print("ok", g["id"])
            # lobby
            lp = await card.new_page()
            await lp.goto(f"http://localhost:{PORT}/index.html", wait_until="load")
            await lp.add_style_tag(content="#dock,#demo,#hint{display:none!important}")
            await lp.wait_for_timeout(5200)
            await lp.screenshot(path=str(ROOT / "share.jpg"), type="jpeg", quality=84); print("ok lobby")
            await b.close()
    finally:
        srv.terminate()

asyncio.run(main())
