"""Bounce Lab: build link-preview images + tags.

For every game in games.js this:
  1. screenshots the game's title screen at phone size
  2. renders a 1200x630 share card (games/<id>/share.jpg)
  3. writes Open Graph / Twitter tags into games/<id>/index.html
And it screenshots the lobby for share.jpg at the site root.

Run from the repo root (needs Python + Playwright + Chrome):
    python3 tools/make_share_images.py
It serves the folder itself on a local port while it works.
"""
import asyncio, base64, html, json, re, subprocess, sys, time
from pathlib import Path
from playwright.async_api import async_playwright

ROOT = Path(__file__).resolve().parent.parent
SITE = "https://az-build.github.io/bounce-lab/"
PORT = 8799
CHROME = "/usr/bin/google-chrome"

def load_games():
    src = (ROOT / "games.js").read_text()
    body = src[src.index("window.BOUNCE_LAB_GAMES =") + len("window.BOUNCE_LAB_GAMES ="):].strip().rstrip(";")
    return json.loads(body)

